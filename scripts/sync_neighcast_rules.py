"""Copy Neighcast's blanket code into static/js/neighcast.js, or check it still matches.

    python3 scripts/sync_neighcast_rules.py          # check (exit 1 if out of date)
    python3 scripts/sync_neighcast_rules.py --write  # copy Neighcast's current code over

Two blocks are copied byte for byte from neighcast/app.js:
  - the blanket rules (LEVELS, CHART, MAX_OK, chartLevel, decide)
  - the forecast code (getJSON, forecastURL, nwsHourly, windChill, nights, soloLevel)
so both sites fetch the same data and make the same call. Never edit neighcast.js; change
Neighcast, then run --write.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NEIGHCAST = ROOT.parent / 'neighcast' / 'app.js'
TARGET = ROOT / 'static' / 'js' / 'neighcast.js'
BLOCKS = [
    ('  // ---------- blanket rules ----------', '  // ---------- forecast'),
    ('  // ---------- forecast', '  // ---------- formatting'),
]
EXPORTS = ('LEVELS', 'CHART', 'MAX_OK', 'chartLevel', 'decide', 'getJSON', 'forecastURL',
           'nwsHourly', 'windChill', 'nights', 'soloLevel')


def neighcast_blocks():
    src = NEIGHCAST.read_text()
    return [src[src.index(a):src.index(b)].rstrip() + '\n' for a, b in BLOCKS]


def render(blocks):
    return (
        '// GENERATED by scripts/sync_neighcast_rules.py: Neighcast\'s blanket rules and forecast code,\n'
        '// copied byte for byte from neighcast/app.js so both sites fetch the same data and make the\n'
        '// same call. Do not edit; change Neighcast, then run the script with --write.\n'
        '(function () {\n  "use strict";\n'
        + '\n'.join(blocks) +
        '  window.Neighcast = { ' + ', '.join(f'{n}: {n}' for n in EXPORTS) + ' };\n'
        '})();\n'
    )


def main():
    if not NEIGHCAST.exists():
        print(f'Neighcast not found at {NEIGHCAST}; nothing to compare.')
        return 0
    wanted = render(neighcast_blocks())
    if '--write' in sys.argv:
        TARGET.write_text(wanted)
        print(f'wrote {TARGET.relative_to(ROOT)}')
        return 0
    if TARGET.exists() and TARGET.read_text() == wanted:
        print('neighcast.js matches Neighcast.')
        return 0
    print('neighcast.js is OUT OF DATE with Neighcast. Run: python3 scripts/sync_neighcast_rules.py --write')
    return 1


if __name__ == '__main__':
    sys.exit(main())
